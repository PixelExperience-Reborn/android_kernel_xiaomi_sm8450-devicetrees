"""The M11A panel commands come from the stock OS3.0.8.0 firmware, per mode."""
import re
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GENERATED = ROOT / "qcom/mondrian-m11a-os3-panel-commands.dtsi"


class M11aOs3PanelCommands(unittest.TestCase):
    def test_generated_from_pinned_stock_firmware(self):
        text = GENERATED.read_text()
        self.assertIn("GENERATED by tools/extract_stock_m11a_commands.py", text)
        self.assertIn("OS3.0.8.0.VMNCNXM", text)
        tool = (ROOT / "tools/extract_stock_m11a_commands.py").read_text()
        for sha in re.findall(r'"([0-9a-f]{64})"', tool):
            self.assertIn(sha[:16], text)

    def test_three_modes_with_stock_packet_counts(self):
        text = GENERATED.read_text()
        self.assertEqual(re.findall(r"(timing@\d) \{ /\* (\d+) Hz \*/", text),
                         [("timing@0", "60"), ("timing@1", "90"), ("timing@2", "120")])
        self.assertEqual(text.count("/* 135 packets */"), 3)
        self.assertEqual(text.count("/* 10 packets */"), 3)
        self.assertIn("qcom,mdss-pan-physical-width-dimension = <695>;", text)
        self.assertIn("qcom,mdss-pan-physical-height-dimension = <1545>;", text)

    def test_included_by_the_m11a_overlay(self):
        overlay = (ROOT / "qcom/mondrian-m11a-primary-overlay.dts").read_text()
        self.assertIn('#include "mondrian-m11a-os3-panel-commands.dtsi"', overlay)


if __name__ == "__main__":
    unittest.main()
