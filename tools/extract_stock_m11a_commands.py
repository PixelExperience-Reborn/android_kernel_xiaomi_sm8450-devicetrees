"""Generate qcom/mondrian-m11a-os3-panel-commands.dtsi from the stock firmware.

The M11A physical size, the panel initialization (qcom,mdss-dsi-on-command) and refresh-rate
switch (qcom,mdss-dsi-timing-switch-command) of every mode are taken from the
stock OS3.0.8.0.VMNCNXM device tree: the Cape DTB of vendor_boot with the
mondrian entry of dtbo applied by fdtoverlay. The inputs are checked against
their sha256 so the output can be reproduced from the official OTA only.
"""
import argparse
import hashlib
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "qcom/mondrian-m11a-os3-panel-commands.dtsi"
PANEL = "/soc/qcom,mdss_mdp@ae00000/qcom,mdss_dsi_m11a_42_02_0a_dsc_cmd"
PROPS = ("qcom,mdss-dsi-on-command", "qcom,mdss-dsi-timing-switch-command")
PANEL_PROPS = ("qcom,mdss-pan-physical-width-dimension", "qcom,mdss-pan-physical-height-dimension")
MONDRIAN_DTBO_INDEX = 19
CAPE_DTB_INDEX = 1


def blobs(data):
    offset = 0
    while True:
        index = data.find(b"\xd0\x0d\xfe\xed", offset)
        if index < 0:
            return
        size = struct.unpack(">I", data[index + 4:index + 8])[0]
        yield data[index:index + size]
        offset = index + size


def dtbo_entry(data, index):
    magic, _total, _hsz, esz, count, eoff = struct.unpack(">6I", data[:24])
    if magic != 0xD7B7AB1E or index >= count:
        raise ValueError("not an Android dtbo image with the mondrian entry")
    size, offset = struct.unpack(">2I", data[eoff + index * esz:eoff + index * esz + 8])
    return data[offset:offset + size]


def fdtget(dtb, path, prop, fmt):
    return subprocess.check_output(["fdtget", "-t", fmt, str(dtb), path, prop], text=True).strip()


def packets(raw):
    out, i = [], 0
    while i < len(raw):
        if i + 7 > len(raw):
            raise ValueError("truncated DSI command header")
        dlen = struct.unpack(">H", raw[i + 5:i + 7])[0]
        out.append(raw[i:i + 7 + dlen])
        i += 7 + dlen
    return out


def dts_bytes(raw, indent):
    lines = [indent + " ".join(f"{b:02X}" for b in packet) for packet in packets(raw)]
    return "[\n" + "\n".join(lines) + "\n" + indent[:-1] + "]"


def generate(vendor_boot_dtb, dtbo):
    vb, dt = Path(vendor_boot_dtb).read_bytes(), Path(dtbo).read_bytes()
    for name, data, expected in (("vendor_boot dtb", vb, PINNED["vendor_boot_dtb"]),
                                 ("dtbo", dt, PINNED["dtbo"])):
        actual = hashlib.sha256(data).hexdigest()
        if actual != expected:
            raise ValueError(f"{name}: sha256 {actual} is not OS3.0.8.0.VMNCNXM")
    with tempfile.TemporaryDirectory() as temp:
        temp = Path(temp)
        base, overlay, full = temp / "cape.dtb", temp / "mondrian.dtbo", temp / "full.dtb"
        base.write_bytes(list(blobs(vb))[CAPE_DTB_INDEX])
        overlay.write_bytes(dtbo_entry(dt, MONDRIAN_DTBO_INDEX))
        if "Mondrian" not in fdtget(overlay, "/", "model", "s"):
            raise ValueError("dtbo entry is not the mondrian overlay")
        subprocess.run(["fdtoverlay", "-i", str(base), "-o", str(full), str(overlay)], check=True)
        panel_props = [f"\t{prop} = <{fdtget(full, PANEL, prop, 'u')}>;" for prop in PANEL_PROPS]
        timings = PANEL + "/qcom,mdss-dsi-display-timings"
        modes = subprocess.check_output(["fdtget", "-l", str(full), timings], text=True).split()
        body = []
        for mode in sorted(modes):
            node = f"{timings}/{mode}"
            rate = int(fdtget(full, node, "qcom,mdss-dsi-panel-framerate", "u"))
            props = []
            for prop in PROPS:
                raw = bytes(int(x, 16) for x in fdtget(full, node, prop, "bx").split())
                props.append(f"\t\t\t/* {len(packets(raw))} packets */\n"
                             f"\t\t\t{prop} = {dts_bytes(raw, chr(9) * 4)};")
            body.append(f"\t\t{mode} {{ /* {rate} Hz */\n" + "\n".join(props) + "\n\t\t};")
    return (
        "// SPDX-License-Identifier: GPL-2.0-only\n"
        "/*\n"
        " * GENERATED by tools/extract_stock_m11a_commands.py - do not edit.\n"
        " *\n"
        " * M11A physical size and the initialization and refresh-rate switch commands of every mode,\n"
        " * from the stock OS3.0.8.0.VMNCNXM device tree (Cape DTB of vendor_boot\n"
        f" * sha256 {PINNED['vendor_boot_dtb'][:16]}..., mondrian entry of dtbo\n"
        f" * sha256 {PINNED['dtbo'][:16]}...). Xiaomi's public M11A source carries an\n"
        " * older 57-packet initialization; stock uses these sequences per mode.\n"
        " */\n\n"
        "&dsi_m11a_42_02_0a_dsc_cmd {\n"
        "\t/* Physical size in 0.1 mm, as stock reports it (DPI). */\n"
        + "\n".join(panel_props) + "\n\n"
        "\tqcom,mdss-dsi-display-timings {\n" + "\n\n".join(body) + "\n\t};\n};\n")


# sha256 of the stock OS3.0.8.0.VMNCNXM inputs.
PINNED = {
    "vendor_boot_dtb": "963e51a382461109392600f2ef804a84d204d6dd0788ced79b5efb68bab00548",
    "dtbo": "8580bc0bbe689784798eec2e055368928b63f1aeb631bb3eaf1c164d878f1d8b",
}


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--vendor-boot-dtb", required=True, type=Path,
                        help="dtb section of the stock vendor_boot (unpack_bootimg)")
    parser.add_argument("--dtbo", required=True, type=Path, help="stock dtbo.img")
    parser.add_argument("--check", action="store_true",
                        help="only verify that the committed file matches the firmware")
    args = parser.parse_args()
    text = generate(args.vendor_boot_dtb, args.dtbo)
    if args.check:
        if OUT.read_text() != text:
            print("[FAIL] qcom/mondrian-m11a-os3-panel-commands.dtsi differs from stock", file=sys.stderr)
            return 1
        print("[PASS] M11A panel commands match OS3.0.8.0.VMNCNXM")
        return 0
    OUT.write_text(text)
    print(f"[PASS] wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
